#!/usr/bin/env python3
"""Turn the stock 3.10 kernel's IR remote tables (`remotectl_button`, the rkxx-remotectl driver) into a
mainline rc-core keymap (development record #302, docs/RK3128-LINUX.md "Board basics").

  rk3128_ir_keymap.py <image> [--c] [--check FILE]

<image> is any of: boot.img.orig, kernel.img.orig (KRNL + zImage), a zImage or a decompressed kernel
(the same inputs as tools/gsl_fw_extract.py, whose LZO and kallsyms code is reused). Read-only.

Without --c it prints the vendor tables and the converted scancodes. With --c it prints the C file
`drivers/media/rc/keymaps/rc-rk3128-reference.c` that linux/patches/302-0002-* adds; --check FILE exits 1
unless FILE is byte-identical to that output (keeps the patch honest).

How the vendor driver reads a frame (remotectl_do_something, read as ARM code): NEC timing (13.5 ms
start, 2.25 ms / 1.125 ms bit), bits are shifted in MSB first, so the first received bit ends up as
bit 15 of a 16-bit group. Group 1 is compared with `usercode` (7 tables, `remotectl_button`); group 2
must satisfy low byte == ~high byte, and its high byte is the table's `scanCode`. rc-core's NEC
decoder gets the same bits LSB first: address = bitrev8(first byte), not_address = bitrev8(second
byte), command = bitrev8(third byte). So, per table (U = usercode, S = scanCode):
    address = bitrev8(U >> 8)    not_address = bitrev8(U & 0xff)    command = bitrev8(S)
and the rc-core scancode is address<<8|command when not_address == ~address (NEC), else
address<<16|not_address<<8|command (extended NEC). Cross-check: mainline's rc-pine64 (the same
0x4040 remote as the vendor's usercode 0x0202) has KEY_POWER 0x40404d = bitrev8(0xb2) and KEY_1
0x404001 = bitrev8(0x80).
"""
import argparse
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gsl_fw_extract as g  # noqa: E402

SYMBOL = "remotectl_button"
ENTRY = 12                  # struct { int usercode; int nbuttons; table *ptr; } (ARM, 3 words)
KEY_H = "/usr/include/linux/input-event-codes.h"


def bitrev8(v):
    return int("{:08b}".format(v)[::-1], 2)


def key_names():
    names = {}
    for line in open(KEY_H):
        m = re.match(r"#define\s+(KEY_\w+)\s+(0x[0-9a-fA-F]+|\d+)\b", line)
        if m:
            names.setdefault(int(m.group(2), 0), m.group(1))
    return names


def read_tables(kern):
    syms = g.kallsyms(kern)
    sym = {n: (a, t) for a, t, n in syms}
    if SYMBOL not in sym:
        sys.exit("no %s in kallsyms" % SYMBOL)
    va, _ = sym[SYMBOL]
    nxt = min(a for a, _t, _n in syms if a > va)
    nent = (nxt - va) // ENTRY
    tabs = []
    for i in range(nent):
        uc, n, ptr = struct.unpack_from("<III", kern, va - g.KERNEL_BASE + i * ENTRY)
        if not (0 < n <= 64 and g.KERNEL_BASE <= ptr < g.KERNEL_BASE + len(kern)):
            break
        keys = [struct.unpack_from("<II", kern, ptr - g.KERNEL_BASE + 8 * j) for j in range(n)]
        tabs.append((uc, keys))
    if not tabs:
        sys.exit("%s did not parse as {usercode, n, ptr} records" % SYMBOL)
    return va, tabs


def convert(uc, sc):
    a0, a1, cmd = bitrev8(uc >> 8), bitrev8(uc & 0xFF), bitrev8(sc)
    if a0 ^ a1 == 0xFF:
        return "NEC", (a0 << 8) | cmd
    return "NECX", (a0 << 16) | (a1 << 8) | cmd


def render_c(tabs, names, src_desc):
    out = ["// SPDX-License-Identifier: GPL-2.0+",
           "",
           "// Keytable for the IR remotes the RK3128 reference board's stock 3.10 kernel (rkxx-remotectl) accepts.",
           "// Generated by tools/rk3128_ir_keymap.py from `remotectl_button` in " + src_desc + ".",
           "// One block per vendor usercode; scancodes are rc-core NEC / extended NEC values.",
           "",
           "#include <media/rc-map.h>",
           "#include <linux/module.h>",
           "",
           "static struct rc_map_table rk3128_reference[] = {"]
    seen = {}
    for uc, keys in tabs:
        out.append("\t/* vendor usercode 0x%04x */" % uc)
        for sc, kc in keys:
            kind, code = convert(uc, sc)
            if code in seen:
                sys.exit("scancode 0x%x twice (usercodes 0x%04x and 0x%04x)" % (code, seen[code], uc))
            seen[code] = uc
            out.append("\t{ 0x%06x, %s }," % (code, names[kc]))
    out += ["};", "",
            "static struct rc_map_list rk3128_reference_map = {",
            "\t.map = {",
            "\t\t.scan     = rk3128_reference,",
            "\t\t.size     = ARRAY_SIZE(rk3128_reference),",
            "\t\t.rc_proto = RC_PROTO_NEC,",
            "\t\t.name     = \"rc-rk3128-reference\",",
            "\t}",
            "};", "",
            "static int __init init_rc_map_rk3128_reference(void)",
            "{",
            "\treturn rc_map_register(&rk3128_reference_map);",
            "}", "",
            "static void __exit exit_rc_map_rk3128_reference(void)",
            "{",
            "\trc_map_unregister(&rk3128_reference_map);",
            "}", "",
            "module_init(init_rc_map_rk3128_reference)",
            "module_exit(exit_rc_map_rk3128_reference)", "",
            "MODULE_LICENSE(\"GPL\");",
            "MODULE_DESCRIPTION(\"RK3128 reference board stock-kernel IR remote keytables\");",
            ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("image")
    ap.add_argument("--c", action="store_true", help="print the C keymap file")
    ap.add_argument("--check", metavar="FILE", help="exit 1 unless FILE equals the generated C file")
    a = ap.parse_args()
    kind, kern = g.unwrap(open(a.image, "rb").read())
    va, tabs = read_tables(kern)
    names = key_names()
    src = "the stock kernel (Linux 3.10.0, %s at 0x%08x)" % (SYMBOL, va)
    if a.c or a.check:
        text = render_c(tabs, names, src)
        if a.check:
            sys.exit(0 if open(a.check).read() == text else 1)
        sys.stdout.write(text)
        return
    print("%s at 0x%08x: %d vendor tables" % (SYMBOL, va, len(tabs)))
    for uc, keys in tabs:
        a0, a1 = bitrev8(uc >> 8), bitrev8(uc & 0xFF)
        print("usercode 0x%04x -> NEC address 0x%02x, second byte 0x%02x (%s), %d keys" % (
            uc, a0, a1, "NEC" if a0 ^ a1 == 0xFF else "extended NEC", len(keys)))
        for sc, kc in keys:
            print("   vendor scan 0x%02x -> scancode 0x%06x  %s" % (sc, convert(uc, sc)[1], names[kc]))


if __name__ == "__main__":
    main()
